@dataclass(frozen=True)
class Example:
    """One evaluation probe. ``category`` is ``"sentence"`` for language examples."""

    id: str
    lang: str
    category: str
    text: str


@dataclass(frozen=True)
class CorpusManifest:
    """Machine-readable description of a written corpus directory."""

    corpus_id: str
    corpus_version: str
    schema_version: str
    seed: int
    n_examples: int
    languages: list[str]
    categories: list[str]
    train_chars: int
    train_lines: int
    train_sha256: str
    eval_sha256: str

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict) -> CorpusManifest:
        return cls(**data)


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def sha256_file(path: str | Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def build_examples() -> list[Example]:
    """The evaluation fixture: language sentences + orthography probe categories."""
    examples: list[Example] = []
    for lang, sentences in EXAMPLE_BANK.items():
        for i, text in enumerate(sentences, start=1):
            examples.append(Example(id=f"{lang}-{i:03d}", lang=lang, category="sentence", text=text))
    for category, items in CATEGORY_BANK.items():
        for i, text in enumerate(items, start=1):
            examples.append(Example(id=f"{category}-{i:03d}", lang="mixed", category=category, text=text))
    return examples


def _sentences_for_language(lang: str, words: Sequence[str], rng: random.Random, count: int) -> list[str]:
    """Build simple, grammatical-ish sentences from a word bank (fixture only)."""
    out: list[str] = []
    for _ in range(count):
        a, b, c = (rng.choice(words) for _ in range(3))
        style = rng.randint(0, 2)
        if style == 0:
            line = f"{a} {b} {c}."
        elif style == 1:
            line = f"{a} {b}, {c} {rng.choice(words)}?"
        else:
            line = f"{a} {rng.choice(words)} {b}; {c}."
        out.append(line)
    return out


def generate_train_text(
    seed: int = 1337,
    sentences_per_language: int = 60,
    english_chars: int = 40_000,
) -> str:
    """Deterministic training text for tokenizer fitting.

    Composition: generated sentences from each language's word bank, numeric/date/math
    variants, English technical lines, code snippets, and the Project 001 synthetic
    English corpus. Deterministic for a fixed seed.
    """
    rng = random.Random(seed)
    blocks: list[str] = []

    for lang, words in WORD_BANK.items():
        blocks.extend(_sentences_for_language(lang, words, rng, sentences_per_language))

    numbers: list[str] = []
    for _ in range(200):
        n = rng.randint(0, 9_999_999)
        numbers.append(rng.choice([str(n), f"{n:,}", f"{n / 100:.2f}", f"{n}%"]))
    for _ in range(120):
        y = rng.randint(1990, 2035)
        m = rng.randint(1, 12)
        d = rng.randint(1, 28)
        numbers.append(rng.choice([f"{y:04d}-{m:02d}-{d:02d}", f"{d:02d}/{m:02d}/{y:04d}", f"{d} March {y}"]))
    for _ in range(80):
        a, b = rng.randint(1, 999), rng.randint(1, 999)
        numbers.append(f"x = {a} + {b} * 2  # {a + b * 2}")
    blocks.extend(numbers)

    blocks.extend(_TECH_LINES * 12)
    blocks.extend(_CODE_LINES * 6)
    blocks.append(generate_corpus(target_chars=english_chars, seed=seed))

    return "\n".join(blocks) + "\n"


def write_corpus(
    out_dir: str | Path,
    seed: int = 1337,
    sentences_per_language: int = 60,
    english_chars: int = 40_000,
) -> CorpusManifest:
    """Write ``train.txt``, ``eval.jsonl`` and ``manifest.json`` into ``out_dir``."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)

    train_text = generate_train_text(
        seed=seed, sentences_per_language=sentences_per_language, english_chars=english_chars
    )
    examples = build_examples()

    train_path = out / "train.txt"
    eval_path = out / "eval.jsonl"
    manifest_path = out / "manifest.json"

    train_path.write_text(train_text, encoding="utf-8")
    eval_path.write_text(
        "\n".join(json.dumps(asdict(ex), ensure_ascii=False) for ex in examples) + "\n",
        encoding="utf-8",
    )

    manifest = CorpusManifest(
        corpus_id=CORPUS_ID,
        corpus_version=CORPUS_VERSION,
        schema_version=SCHEMA_VERSION,
        seed=seed,
        n_examples=len(examples),
        languages=sorted(EXAMPLE_BANK),
        categories=sorted(CATEGORY_BANK),
        train_chars=len(train_text),
        train_lines=train_text.count("\n"),
        train_sha256=sha256_text(train_text),
        eval_sha256=sha256_file(eval_path),
    )
    manifest_path.write_text(json.dumps(manifest.to_dict(), indent=2) + "\n", encoding="utf-8")
    return manifest


def load_corpus(corpus_dir: str | Path) -> tuple[list[Example], CorpusManifest]:
    """Read a corpus directory written by :func:`write_corpus`."""
    base = Path(corpus_dir)
    manifest_path = base / "manifest.json"
    eval_path = base / "eval.jsonl"
    if not manifest_path.exists():
        raise FileNotFoundError(f"corpus manifest not found: {manifest_path} (run the prepare-corpus CLI)")
    if not eval_path.exists():
        raise FileNotFoundError(f"evaluation fixture not found: {eval_path}")

    manifest = CorpusManifest.from_dict(json.loads(manifest_path.read_text(encoding="utf-8")))
    examples = [
        Example(**json.loads(line))
        for line in eval_path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]

    # fail loudly instead of silently benchmarking against a mutated fixture
    actual = sha256_file(eval_path)
    if actual != manifest.eval_sha256:
        raise ValueError(
            f"evaluation fixture hash mismatch: manifest says {manifest.eval_sha256[:12]}…, "
            f"file is {actual[:12]}… — the corpus was modified after it was written"
        )
    return examples, manifest


def examples_by_language(examples: Iterable[Example]) -> dict[str, list[Example]]:
    out: dict[str, list[Example]] = {}
    for ex in examples:
        out.setdefault(ex.lang, []).append(ex)
    return out


