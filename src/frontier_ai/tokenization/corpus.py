"""Deterministic research corpora for tokenizer analysis.

Two *disjoint* artifacts are produced by this module:

1. ``train.txt`` — text used to **train** a tokenizer. It is generated deterministically
   from small curated word lists per language plus the Project 001 English synthetic
   corpus generator.
2. ``eval.jsonl`` — a hand-written **evaluation fixture** of representative examples
   (one JSON object per line: ``id``, ``lang``, ``category``, ``text``).

CRITICAL LIMITATIONS — read before quoting any number produced with this corpus:

* This is an **evaluation fixture, not a training corpus**. It contains a few hundred
  short strings, not millions of documents.
* It does **not** represent the statistical distribution of any language. It is a
  hand-written probe set designed to expose tokenizer *behaviour* (how scripts, digits,
  punctuation and mixing are handled), not to measure real-world quality.
* Training text is generated from small word lists that **overlap** with the words used
  in the evaluation examples. Compression numbers measured on this fixture are therefore
  *optimistic* and are only comparable between tokenizers measured on the same fixture.
* No web scraping, no private data, no copyrighted text. Every string here is written by
  the project authors or generated by our own deterministic code.
"""

